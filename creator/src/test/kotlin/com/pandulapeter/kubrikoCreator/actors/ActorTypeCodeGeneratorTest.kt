package com.pandulapeter.kubrikoCreator.actors

import kotlin.test.Test
import kotlin.test.assertContains
import kotlin.test.assertEquals
import kotlin.test.assertFalse
import kotlin.test.assertTrue

class ActorTypeCodeGeneratorTest {
    private val packageName = "com.example.game"

    private fun generate(vararg events: EventDefinition, shape: ActorShape = ActorShape.CIRCLE) = ActorTypeCodeGenerator.generateActorType(
        ActorTypeDefinition(name = "Player", shape = shape, color = 0xFF5AB06A, width = 60f, height = 30f, events = events.toList()),
        packageName,
    )

    @Test
    fun theClassGoesIntoTheGeneratedPackageWithAHeaderPointingToItsDefinition() {
        val code = generate()
        assertTrue(code.startsWith("// Generated by Kubriko Creator from .kubriko/actors/Player.json."))
        assertContains(code, "package com.example.game.generated\n")
        assertContains(code, "class Player private constructor(state: State) : Visible, Dynamic, Collidable, Editable<Player> {")
    }

    @Test
    fun theDefinitionsAppearanceBecomesTheStatesDefaultsAndTheSceneEditorsInitialSize() {
        val code = generate()
        assertContains(code, "@SerialName(\"color\") val color: SerializableColor = Color(0xFF5AB06A),")
        assertContains(code, "EditableMetadata.create<Player, State>(typeId = \"Player\")")
        assertContains(code, "initialSize = SceneSize(60f.sceneUnit, 30f.sceneUnit)")
    }

    @Test
    fun theShapeDecidesHowTheActorDraws() {
        assertContains(generate(shape = ActorShape.CIRCLE), "drawCircle(")
        assertContains(generate(shape = ActorShape.RECTANGLE), "drawRect(")
    }

    @Test
    fun addedToSceneBlocksRunAfterTheManagersAreResolved() {
        val code = generate(EventDefinition(EventType.ADDED_TO_SCENE, blocks = listOf(BlockDefinition.SetVelocity(240f, 180f))))
        val onAdded = code.substringAfter("override fun onAdded(kubriko: Kubriko) {").substringBefore("\n    }")
        assertTrue(onAdded.indexOf("viewportManager = kubriko.get()") < onAdded.indexOf("velocity = SceneOffset(240f.sceneUnit, 180f.sceneUnit)"), onAdded)
        assertContains(onAdded, "// When added to the Scene")
    }

    @Test
    fun everyFrameBlocksRunBeforeTheActorMoves() {
        val update = generate(EventDefinition(EventType.EVERY_FRAME, blocks = listOf(BlockDefinition.Stop)))
            .substringAfter("override fun update(").substringBefore("\n    }")
        assertTrue(update.indexOf("velocity = SceneOffset.Zero") < update.indexOf("body.position += velocity * (deltaTimeInMilliseconds / 1000f)"), update)
    }

    @Test
    fun edgeHandlingIsOnlyGeneratedWhenAnEdgeEventExists() {
        assertFalse("isTouchingLeftEdge" in generate())
        assertFalse("constrainedWithin" in generate())
        val code = generate(EventDefinition(EventType.EDGE_TOUCHED, blocks = listOf(BlockDefinition.BounceOffEdge)))
        assertContains(code, "import com.pandulapeter.kubriko.helpers.extensions.constrainedWithin")
        assertContains(code, "body.position = body.position.constrainedWithin(topLeft, bottomRight)")
        assertContains(code, "if (isTouchingRightEdge) velocity = SceneOffset(-velocity.x.raw.absoluteValue.sceneUnit, velocity.y)")
        assertContains(code, "import kotlin.math.absoluteValue")
    }

    @Test
    fun anActorRestingAtTheEdgeDoesNotTouchItAgain() {
        val code = generate(EventDefinition(EventType.EDGE_TOUCHED, blocks = listOf(BlockDefinition.Stop)))
        assertContains(code, "val isTouchingLeftEdge = body.position.x < topLeft.x")
        assertContains(code, "val isTouchingRightEdge = body.position.x > bottomRight.x")
        assertContains(code, "val isTouchingTopEdge = body.position.y < topLeft.y")
        assertContains(code, "val isTouchingBottomEdge = body.position.y > bottomRight.y")
    }

    @Test
    fun keyEventsMakeTheActorKeyboardAwareAndShareOneBranchPerKey() {
        assertFalse("KeyboardInputAware" in generate())
        val code = generate(
            EventDefinition(EventType.KEY_PRESSED, KeyChoice.SPACE, blocks = listOf(BlockDefinition.Stop)),
            EventDefinition(EventType.KEY_PRESSED, KeyChoice.LEFT, blocks = listOf(BlockDefinition.AddToVelocity(-50f, 0f))),
            EventDefinition(EventType.KEY_PRESSED, KeyChoice.SPACE, blocks = listOf(BlockDefinition.RemoveSelf)),
        )
        assertContains(code, ", KeyboardInputAware {")
        assertContains(code, "import androidx.compose.ui.input.key.Key\n")
        assertEquals(1, Regex("Key.Spacebar ->").findAll(code).count())
        val spaceBranch = code.substringAfter("Key.Spacebar -> {").substringBefore("}")
        assertTrue(spaceBranch.indexOf("velocity = SceneOffset.Zero") < spaceBranch.indexOf("actorManager.remove(this)"), spaceBranch)
        assertTrue(code.indexOf("Key.DirectionLeft") < code.indexOf("Key.Spacebar"), "Keys follow the order of the key list")
    }

    @Test
    fun aKeyEventWithoutAKeyIsIgnored() {
        assertFalse("KeyboardInputAware" in generate(EventDefinition(EventType.KEY_PRESSED, key = null, blocks = listOf(BlockDefinition.Stop))))
    }

    @Test
    fun everyBlockBecomesItsStatement() {
        assertEquals(listOf("velocity = SceneOffset(1.5f.sceneUnit, -2f.sceneUnit)"), ActorTypeCodeGenerator.blockLines(BlockDefinition.SetVelocity(1.5f, -2f), EventType.EVERY_FRAME, "Ball"))
        assertEquals(listOf("velocity += SceneOffset(0f.sceneUnit, 3f.sceneUnit)"), ActorTypeCodeGenerator.blockLines(BlockDefinition.AddToVelocity(0f, 3f), EventType.EVERY_FRAME, "Ball"))
        assertEquals(listOf("velocity = SceneOffset.Zero"), ActorTypeCodeGenerator.blockLines(BlockDefinition.Stop, EventType.EVERY_FRAME, "Ball"))
        assertEquals(listOf("body.position = SceneOffset(-10f.sceneUnit, 10f.sceneUnit)"), ActorTypeCodeGenerator.blockLines(BlockDefinition.JumpTo(-10f, 10f), EventType.EVERY_FRAME, "Ball"))
        assertEquals(listOf("actorManager.remove(this)"), ActorTypeCodeGenerator.blockLines(BlockDefinition.RemoveSelf, EventType.EVERY_FRAME, "Ball"))
        assertEquals(4, ActorTypeCodeGenerator.blockLines(BlockDefinition.BounceOffEdge, EventType.EDGE_TOUCHED, "Ball").size)
    }

    @Test
    fun bouncingOutsideTheEdgeEventLeavesOnlyAnExplanation() {
        val lines = ActorTypeCodeGenerator.blockLines(BlockDefinition.BounceOffEdge, EventType.EVERY_FRAME, "Ball")
        assertTrue(lines.all { it.startsWith("//") }, lines.toString())
    }

    @Test
    fun logBlocksWriteToKubrikosLoggerWithTheActorTypeAsTheirSource() {
        assertEquals(
            listOf("Logger.log(message = \"Say \\\"\\\$hi\\\" \\\\ to\\neveryone\", source = \"Ball\")"),
            ActorTypeCodeGenerator.blockLines(BlockDefinition.Log("Say \"\$hi\" \\ to\neveryone"), EventType.EVERY_FRAME, "Ball"),
        )
        assertContains(generate(EventDefinition(EventType.EVERY_FRAME, blocks = listOf(BlockDefinition.Log("Hello")))), "import com.pandulapeter.kubriko.logger.Logger")
        assertFalse("Logger" in generate(EventDefinition(EventType.EVERY_FRAME, blocks = listOf(BlockDefinition.Stop))))
    }

    @Test
    fun kotlinBlocksAreInsertedVerbatimInAScopeOfTheirOwn() {
        assertEquals(
            listOf("run {", "    val speed = velocity.x", "", "    if (speed > 0f.sceneUnit) {", "        velocity = SceneOffset.Zero", "    }", "}"),
            ActorTypeCodeGenerator.blockLines(BlockDefinition.Kotlin("\n\nval speed = velocity.x   \n\nif (speed > 0f.sceneUnit) {\n    velocity = SceneOffset.Zero\n}\n\n"), EventType.EVERY_FRAME, "Ball"),
        )
        assertContains(
            generate(EventDefinition(EventType.EVERY_FRAME, blocks = listOf(BlockDefinition.Kotlin("velocity = SceneOffset.Zero\nprintln(1)")))),
            "        run {\n            velocity = SceneOffset.Zero\n            println(1)\n        }\n",
        )
    }

    @Test
    fun anEmptyKotlinBlockGeneratesNothing() {
        assertEquals(emptyList(), ActorTypeCodeGenerator.blockLines(BlockDefinition.Kotlin(" \n "), EventType.EVERY_FRAME, "Ball"))
    }

    @Test
    fun numbersAlwaysBecomeValidKotlinFloatLiterals() {
        assertEquals("240f", ActorTypeCodeGenerator.floatLiteral(240f))
        assertEquals("-0.5f", ActorTypeCodeGenerator.floatLiteral(-0.5f))
        assertEquals("1.0E-4f", ActorTypeCodeGenerator.floatLiteral(1e-4f))
        assertEquals("1.0E10f", ActorTypeCodeGenerator.floatLiteral(1e10f))
        assertEquals("0f", ActorTypeCodeGenerator.floatLiteral(Float.NaN))
        assertEquals("0f", ActorTypeCodeGenerator.floatLiteral(Float.POSITIVE_INFINITY))
    }

    @Test
    fun colorsBecomeEightDigitHexLiterals() {
        assertEquals("0xFF6060AA", ActorTypeCodeGenerator.colorLiteral(0xFF6060AA))
        assertEquals("0x00000001", ActorTypeCodeGenerator.colorLiteral(1L))
        assertEquals("0xFFFFFFFF", ActorTypeCodeGenerator.colorLiteral(-1L))
    }

    @Test
    fun theRegistryListsEveryActorTypeAlphabetically() {
        val registry = ActorTypeCodeGenerator.generateRegistry(listOf("Wall", "Ball"), packageName)
        assertContains(registry, "package com.example.game.generated\n")
        assertContains(registry, "object GeneratedActorTypes {")
        assertContains(registry, "        Ball.metadata,\n        Wall.metadata,\n")
    }

    @Test
    fun anEmptyRegistryStillCompiles() {
        assertContains(ActorTypeCodeGenerator.generateRegistry(emptyList(), packageName), "val metadata: List<EditableMetadata<*>> = emptyList()")
    }

    @Test
    fun theOutputIsTheSameEveryTime() {
        val events = EventType.entries.map { EventDefinition(it, KeyChoice.A, blocks = listOf(BlockDefinition.Stop)) }.toTypedArray()
        assertEquals(generate(*events), generate(*events))
    }

    @Test
    fun everyActorTypeIsCollidableWithAMaskMatchingItsShape() {
        val circle = generate(shape = ActorShape.CIRCLE)
        assertContains(circle, "override val collisionMask = CircleCollisionMask(")
        assertContains(circle, "initialRadius = body.size.width / 2,")
        val rectangle = generate(shape = ActorShape.RECTANGLE)
        assertContains(rectangle, "override val collisionMask = BoxCollisionMask(")
        assertContains(rectangle, "import com.pandulapeter.kubriko.collision.mask.BoxCollisionMask")
        assertFalse("CircleCollisionMask" in rectangle)
        val update = circle.substringAfter("override fun update(").substringBefore("\n    }")
        assertTrue(update.trimEnd().endsWith("collisionMask.position = body.position"), update)
    }

    @Test
    fun collisionEventsMakeACollisionDetectorWithOneBranchPerOtherActorType() {
        val code = ActorTypeCodeGenerator.generateActorType(
            ActorTypeDefinition(
                name = "Ball",
                events = listOf(
                    EventDefinition(EventType.COLLISION, otherActorType = "Paddle", blocks = listOf(BlockDefinition.BounceOffOther)),
                    EventDefinition(EventType.COLLISION, otherActorType = "Brick", blocks = listOf(BlockDefinition.RemoveOther)),
                    EventDefinition(EventType.COLLISION, otherActorType = "Paddle", blocks = listOf(BlockDefinition.Stop)),
                ),
            ),
            packageName,
            knownActorTypeNames = listOf("Ball", "Brick", "Paddle"),
        )
        assertContains(code, ": Visible, Dynamic, CollisionDetector, Editable<Ball> {")
        assertContains(code, "override val collidableTypes: List<KClass<out Collidable>> = listOf(Brick::class, Paddle::class)")
        assertContains(code, "when (val other = collidables[index]) {")
        assertEquals(1, Regex("is Paddle ->").findAll(code).count())
        val paddleBranch = code.substringAfter("is Paddle -> {").substringBefore("\n                }")
        assertTrue(paddleBranch.indexOf("val offset = body.position - other.body.position") < paddleBranch.indexOf("velocity = SceneOffset.Zero"), paddleBranch)
        assertContains(code.substringAfter("is Brick -> {"), "actorManager.remove(other)")
        assertContains(code, "import com.pandulapeter.kubriko.types.SceneUnit")
    }

    @Test
    fun collisionEventsWithUnknownOrMissingActorTypesAreLeftOut() {
        val code = ActorTypeCodeGenerator.generateActorType(
            ActorTypeDefinition(
                name = "Ball",
                events = listOf(
                    EventDefinition(EventType.COLLISION, otherActorType = "Deleted", blocks = listOf(BlockDefinition.Stop)),
