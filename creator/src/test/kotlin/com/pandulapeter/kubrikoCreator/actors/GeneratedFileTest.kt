package com.pandulapeter.kubrikoCreator.actors

import kotlin.test.Test
import kotlin.test.assertFalse
import kotlin.test.assertTrue

class GeneratedFileTest {
    private val generated = GeneratedFile.withHeader(" from .kubriko/actors/Ball.json", "package game\n\nclass Ball\n")

    @Test
    fun aFileJustGeneratedIsUnchanged() {
        assertTrue(GeneratedFile.isUnchanged(generated))
        assertTrue(GeneratedFile.isUnchanged(ActorTypeCodeGenerator.generateActorType(ActorTypeDefinition(name = "Ball"), "game")))
        assertTrue(GeneratedFile.isUnchanged(ActorTypeCodeGenerator.generateRegistry(listOf("Ball"), "game")))
    }

    @Test
    fun anyEditToTheCodeIsNoticed() {
        assertFalse(GeneratedFile.isUnchanged(generated.replace("class Ball", "class Ball // tweaked")))
        assertFalse(GeneratedFile.isUnchanged(generated + "\nfun extra() = Unit\n"))
    }

    @Test
    fun filesGeneratedBeforeChecksumsCountAsUnchanged() {
        assertTrue(GeneratedFile.isUnchanged("// Generated by Kubriko Creator from .kubriko/actors/Ball.json. Edit it in Kubriko Creator.\npackage game\n"))
    }

    @Test
    fun aFileWithoutTheHeaderIsNotCreatorsAnyMore() {
        assertFalse(GeneratedFile.isUnchanged("package game\n\nclass Ball\n"))
    }
}
