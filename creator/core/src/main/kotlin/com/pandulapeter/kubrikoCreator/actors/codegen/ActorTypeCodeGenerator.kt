import com.pandulapeter.kubrikoCreator.actors.ActorTypeDefinition
import com.pandulapeter.kubrikoCreator.actors.ActorTypeFamily
import com.pandulapeter.kubrikoCreator.actors.BlockScope
import com.pandulapeter.kubrikoCreator.actors.BlockTypeKind
import com.pandulapeter.kubrikoCreator.actors.DefinitionPaths
import com.pandulapeter.kubrikoCreator.actors.GeneratedNames
import com.pandulapeter.kubrikoCreator.actors.ManagerTypeDefinition
import com.pandulapeter.kubrikoCreator.actors.PropertyDefinition
import com.pandulapeter.kubrikoCreator.actors.PropertyKind
import com.pandulapeter.kubrikoCreator.actors.SpriteFiles
import com.pandulapeter.kubrikoCreator.actors.codegen.BlockCodeGenerator.colorLiteral
import com.pandulapeter.kubrikoCreator.actors.codegen.BlockCodeGenerator.initialValueLiteral
import com.pandulapeter.kubrikoCreator.actors.codegen.BlockCodeGenerator.stringLiteral
import com.pandulapeter.kubrikoCreator.actors.codegen.BlockCodeGenerator.unitLiteral

/**
 * Turns block-built Actor types into ordinary Kotlin: one class per type, plus a registry of all of them.
 *
 * The output is meant to read like hand-written code, so "Convert to code" leaves something a person would keep.
 */
public object ActorTypeCodeGenerator {

    public const val GENERATED_PACKAGE: String = "generated"
    public const val REGISTRY_NAME: String = GeneratedNames.ACTOR_TYPES

    /**
     * @param knownActorTypeNames Every Actor type of the project: collision Events with any other Actor type (one that
     *   was deleted, or not chosen yet) are left out, so that the generated code always compiles.
     * @param managerTypes Every Manager type of the project, whose Properties the Blocks may use.
     * @param collidableActorTypeNames The Actor types that get a collision mask ([PluginManagers.collidableActorTypeNames]).
     * @param actorTypes Every Actor type of the project, for the families parents make: a type in one is generated by
     *   [ActorFamilyCodeGenerator].
     * @param family The families of [actorTypes], passed in when every type of a project is generated at once.
     */
    internal fun generateActorType(
        definition: ActorTypeDefinition,
        packageName: String,
        knownActorTypeNames: List<String> = listOf(definition.name),
        managerTypes: List<ManagerTypeDefinition> = emptyList(),
        collidableActorTypeNames: Set<String> = emptySet(),
        actorTypes: List<ActorTypeDefinition> = listOf(definition),
        family: ActorTypeFamily = ActorTypeFamily(actorTypes),
    ): String {
        val name = definition.name
        if (family.parentOf(name) != null || family.hasChildren(name)) {
            return ActorFamilyCodeGenerator.generate(definition, packageName, actorTypes, managerTypes, collidableActorTypeNames, family)
        }
        val scope = BlockScope(
            typeName = name,
            kind = BlockTypeKind.ACTOR,
            properties = definition.properties,
            actorTypeNames = knownActorTypeNames,
            managerTypes = managerTypes,
            baseClassNames = family.namesWithChildren,
        )
        val role = ActorClassEmitter.Role.STANDALONE
        val features = ActorTypeFeatures(
            events = definition.events,
            scope = scope,
            shapes = setOf(definition.shape),
            hasSprite = definition.sprite?.let(SpriteFiles::accessorOf) != null,
            isCollidableAnyway = name in collidableActorTypeNames,
            isFamily = role.isFamily,
        )
        val imports = mutableSetOf<String>()
        val code = buildString {
            with(ActorClassEmitter(features, role, scope, family, imports)) { appendClass(definition, definition.properties, packageName) }
        }
        return GeneratedFile.withHeader(" from ${DefinitionPaths.definitionPath(definition)}", buildString {
            appendLine("package $packageName.$GENERATED_PACKAGE")
            appendLine()
            imports.sorted().forEach { appendLine("import $it") }
            appendLine()
            append(code)
        })
    }

    /**
     * The look of an Actor type's final class, which Kubriko draws together with the batched Actors around it: its shape
     * in its color, or its sprite. The look is brought up to date with the Actor whenever Kubriko reads it, so a color
     * changed by a Block or in the Scene editor shows on the next frame.
     */
    internal fun StringBuilder.appendLook(definition: ActorTypeDefinition, imports: MutableSet<String>) {
        val isSprite = definition.sprite?.let(SpriteFiles::accessorOf) != null
        imports += if (isSprite) SPRITE_LOOK_IMPORTS else listOf(LOOKS_PACKAGE + lookClassOf(definition.shape))
        appendLine()
        appendLine(if (isSprite) SPRITE_LOOK else shapeLook(definition.shape))
    }

    /**
     * The part of an Actor type's class that keeps its state: [save], its `State` (with [properties], its own and
     * inherited ones, at their initial values), and the companion with its sprite and Scene metadata.
     */
    internal fun StringBuilder.appendSavedState(definition: ActorTypeDefinition, properties: List<PropertyDefinition>, packageName: String, imports: MutableSet<String>) {
        val spriteAccessor = definition.sprite?.let(SpriteFiles::accessorOf)
        imports += SAVED_STATE_IMPORTS
        if (spriteAccessor != null) imports += listOf("$packageName.resources.Res", "$packageName.resources.allDrawableResources")
        appendLine()
        appendLine("    override fun save() = State(")
        appendLine("        body = body,")
        appendLine("        color = color,")
        properties.forEach { appendLine("        ${it.name} = ${it.name},") }
        appendLine("    )")
        appendLine()
        appendLine("    @kotlinx.serialization.Serializable")
        appendLine("    data class State(")
        appendLine("        @SerialName(\"body\") val body: SerializableBoxBody = BoxBody(),")
        appendLine("        @SerialName(\"color\") val color: SerializableColor = Color(${colorLiteral(definition.color)}),")
        properties.forEach { property ->
            appendLine("        @SerialName(${stringLiteral(property.name)}) val ${property.name}: ${PropertyKind.of(property).kotlinType} = ${initialValueLiteral(property)},")
        }
        appendLine("    ) : Serializable.State<${definition.name}> {")
        appendLine()
        appendLine("        override fun restore() = ${definition.name}(this)")
        appendLine()
        appendLine("        override fun serialize() = Json.encodeToString(this)")
        appendLine("    }")
        appendLine()
        appendLine("    companion object {")
        if (spriteAccessor != null) {
            // Looked up by name rather than through its accessor, so the game still compiles once the image is gone.
            appendLine("        private val sprite = Res.allDrawableResources[${stringLiteral(spriteAccessor)}]")
            appendLine()
        }
        appendLine("        val metadata = EditableMetadata.create<${definition.name}, State>(typeId = \"${definition.name}\") { position ->")
        appendLine("            State(body = BoxBody(initialPosition = position, initialSize = SceneSize(${unitLiteral(definition.width)}, ${unitLiteral(definition.height)})))")
        appendLine("        }")
        appendLine("    }")
    }

    /**
     * The registry of every block-built Actor type, plus the Scene settings ([SceneSettingsCodeGenerator]).
     */
    internal fun generateRegistry(actorTypeNames: List<String>, packageName: String) = GeneratedFile.withHeader("", buildString {
        appendLine("package $packageName.$GENERATED_PACKAGE")
        appendLine()
        appendLine("import com.pandulapeter.kubriko.sceneEditor.EditableMetadata")
        appendLine()
        appendLine("/**")
        appendLine(" * The Scene metadata of every Actor type built in Kubriko Creator, and of the Scene settings.")
        appendLine(" */")
        appendLine("object $REGISTRY_NAME {")
        appendLine("    val metadata: List<EditableMetadata<*>> = listOf(")
        (actorTypeNames + SceneSettingsCodeGenerator.SETTINGS_NAME).sorted().forEach { appendLine("        $it.metadata,") }
        appendLine("    )")
        appendLine("}")
    })

    private fun lookClassOf(shape: ActorShape) = when (shape) {
        ActorShape.CIRCLE -> "EllipseLook"
        ActorShape.RECTANGLE -> "RectangleLook"
    }

    private fun shapeLook(shape: ActorShape) = """
        |    /**
        |     * Its shape in its color.
        |     */
        |    override val look = ${lookClassOf(shape)}(color)
        |        get() {
        |            field.color = color
        |            return field
        |        }
    """.trimMargin()

    internal const val SPRITE_MANAGER_FIELD = "spriteManager"

    private const val LOOKS_PACKAGE = "com.pandulapeter.kubriko.actor.looks."

    /**
     * The sprite stretched over the body, its pixels kept sharp, as pixel art wants them: a part of the shared images the
     * game's sprites are loaded onto ([SpritesCodeGenerator]), so nothing is drawn until they are loaded.
     */
    private val SPRITE_LOOK = """
        |    /**
        |     * Its sprite, once the game's sprites are loaded.
        |     */
        |    override val look = SpriteLook(texture = null, filterQuality = FilterQuality.None)
        |        get() {
        |            field.setRegion(sprite?.let { $SPRITE_MANAGER_FIELD.getRegion(it) })
        |            return field
        |        }
    """.trimMargin()

    private val SPRITE_LOOK_IMPORTS = listOf(
        "androidx.compose.ui.graphics.FilterQuality",
        "${LOOKS_PACKAGE}SpriteLook",
        "com.pandulapeter.kubriko.sprites.setRegion",
    )

    /**
     * What the part of an Actor type's final class that keeps its state ([appendSavedState]) uses.
     */
    private val SAVED_STATE_IMPORTS = listOf(
        "androidx.compose.ui.graphics.Color",
        "com.pandulapeter.kubriko.actor.body.BoxBody",
        "com.pandulapeter.kubriko.helpers.extensions.sceneUnit",
        "com.pandulapeter.kubriko.sceneEditor.EditableMetadata",
        "com.pandulapeter.kubriko.serialization.Serializable",
        "com.pandulapeter.kubriko.serialization.typeSerializers.SerializableBoxBody",
        "com.pandulapeter.kubriko.serialization.typeSerializers.SerializableColor",
        "com.pandulapeter.kubriko.types.SceneSize",
        "kotlinx.serialization.SerialName",
        "kotlinx.serialization.json.Json",
    )
}
